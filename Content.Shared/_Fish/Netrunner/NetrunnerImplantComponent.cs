using Content.Shared.DoAfter;
using Robust.Shared.Map;
using Robust.Shared.Prototypes;

namespace Content.Shared._Fish.Netrunner;

/// <summary>Implant configuration and authoritative resources, retained when extracted.</summary>
[RegisterComponent]
public sealed partial class NetrunnerImplantComponent : Component
{
    [DataField] public float MaxRam = 12;
    [DataField] public float MaxOverload = 4;
    [DataField] public float RamPerSecond = 0.1f;
    [DataField] public float TracePerSecond = 0.1f;
    [DataField] public TimeSpan RecoveryDelay = TimeSpan.FromSeconds(8);
    [DataField] public TimeSpan GlobalCooldown = TimeSpan.FromSeconds(3);
    /// <summary>Administrative demonstration mode with free, instant programs.</summary>
    [DataField] public bool DebugMode;
    /// <summary>Body temperature increase per RAM reserved by a normal activation.</summary>
    [DataField] public float HeatPerRam = 0.18f;
    /// <summary>Price of a physical cooldown accelerator in the private shop.</summary>
    [DataField] public int VisorPrice = 30;
    /// <summary>Prevents duplicate physical visor purchases from one implant.</summary>
    [ViewVariables] public bool VisorPurchased;
    [DataField] public List<ProtoId<NetrunnerAbilityPrototype>> Abilities = new();
    /// <summary>Initial credit, granted once when this implant is first installed.</summary>
    [DataField] public int StartingLinks = 12;
    /// <summary>Maximum number of memory expansion purchases.</summary>
    [DataField] public int MaxMemoryUpgrades = 3;
    /// <summary>RAM capacity added by each memory expansion, initially empty.</summary>
    [DataField] public float MemoryPerUpgrade = 2;
    /// <summary>Maximum number of activation acceleration purchases.</summary>
    [DataField] public int MaxSpeedUpgrades = 3;
    /// <summary>Additive cast time reduction per acceleration purchase.</summary>
    [DataField] public float SpeedPerUpgrade = 0.1f;
    /// <summary>Price of the first hardware upgrade.</summary>
    [DataField] public int UpgradeBaseCost = 6;
    /// <summary>Price increase for each subsequent upgrade of the same type.</summary>
    [DataField] public int UpgradeCostStep = 4;
    /// <summary>Credits retained with the extracted implant.</summary>
    [ViewVariables] public int NeuralLinks;
    /// <summary>Installed memory expansions.</summary>
    [ViewVariables] public int MemoryUpgrades;
    /// <summary>Installed activation accelerators.</summary>
    [ViewVariables] public int SpeedUpgrades;
    /// <summary>Total passive credits generated by this implant.</summary>
    public int PassiveLinks;
    /// <summary>Purchased programs, retained across extraction.</summary>
    public readonly HashSet<ProtoId<NetrunnerAbilityPrototype>> UnlockedAbilities = new();
    /// <summary>Devices already used to earn a research credit.</summary>
    public readonly HashSet<EntityUid> ResearchedDevices = new();
    [ViewVariables] public float Ram;
    [ViewVariables] public float Trace;
    /// <summary>Prevents resource resets when the implant is removed and installed again.</summary>
    public bool ResourcesInitialized;
    public EntityUid? User;
    public TimeSpan LastUpdate;
    public TimeSpan RecoverAt;
    public TimeSpan ReadyAt;
    public TimeSpan LastHackAt;
    public int BurstCount;
    public int TraceTier;
    public readonly Dictionary<ProtoId<NetrunnerAbilityPrototype>, TimeSpan> Cooldowns = new();
    public readonly List<EntityUid> GrantedActions = new();
    public readonly List<NetrunnerLogEntry> Journal = new();
    public NetrunnerPendingHack? Pending;
    public DoAfterId? Connection;
    public EntityUid? Chair;
    public EntityUid? Camera;
    /// <summary>Mobile, nonphysical viewer controlled through the body.</summary>
    public EntityUid? RemoteEye;
    /// <summary>The body's original eye settings, restored on disconnection.</summary>
    public EntityUid? OriginalEyeTarget;
    public bool OriginalDrawFov;
    /// <summary>Next passive compilation credit deadline.</summary>
    public TimeSpan NextLinkAt;
    public TimeSpan NextConnectionCharge;
    public TimeSpan NextCameraSwitch;
    public TimeSpan NextUiUpdate;
}

/// <summary>One in-flight program and its fixed execution context.</summary>
public sealed class NetrunnerPendingHack
{
    public required ProtoId<NetrunnerAbilityPrototype> Ability;
    public required EntityUid Target;
    public required EntityUid Device;
    public required EntityUid Origin;
    /// <summary>Movement of the remote viewer interrupts an in-flight program.</summary>
    public required EntityCoordinates OriginCoordinates;
    public required TimeSpan FinishesAt;
    /// <summary>Fixed location chosen for an area activation.</summary>
    public EntityCoordinates? AreaCoordinates;
    /// <summary>Candidate lights gathered once, then validated again at completion.</summary>
    public List<EntityUid>? AreaTargets;
    public DoAfterId? DoAfter;
}
