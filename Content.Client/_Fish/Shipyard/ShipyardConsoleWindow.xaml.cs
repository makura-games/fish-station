using Content.Client.UserInterface.Controls;
using Content.Shared._Fish.Shipyard;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Fish.Shipyard;

[GenerateTypedNameReferences]
public sealed partial class ShipyardConsoleWindow : FancyWindow
{
    public event Action<string>? OnPurchasePressed;

    public ShipyardConsoleWindow()
    {
        RobustXamlLoader.Load(this);
    }

    public void UpdateState(ShipyardConsoleBoundUserInterfaceState state)
    {
        BalanceLabel.Text = Loc.GetString("shipyard-console-balance-value", ("amount", state.Balance));

        if (!string.IsNullOrWhiteSpace(state.StatusMessage))
        {
            StatusLabel.Visible = true;
            StatusLabel.Text = state.StatusMessage;
        }
        else
        {
            StatusLabel.Visible = false;
        }

        VesselsContainer.DisposeAllChildren();

        foreach (var vessel in state.Vessels)
        {
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
                SeparationOverride = 2,
            };

            row.AddChild(new Label
            {
                Text = vessel.Name,
                StyleClasses = { "LabelKeyText" },
            });

            if (!string.IsNullOrWhiteSpace(vessel.Description))
            {
                row.AddChild(new Label
                {
                    Text = vessel.Description,
                });
            }

            row.AddChild(new Label
            {
                Text = Loc.GetString("shipyard-console-cost", ("amount", vessel.Price)),
            });

            if (!string.IsNullOrWhiteSpace(vessel.UnavailableReason))
            {
                row.AddChild(new Label
                {
                    Text = vessel.UnavailableReason,
                    FontColorOverride = Color.OrangeRed,
                });
            }

            var vesselId = vessel.PrototypeId;
            var button = new Button
            {
                Text = state.Purchasing
                    ? Loc.GetString("shipyard-console-purchasing")
                    : Loc.GetString("shipyard-console-purchase"),
                Disabled = !vessel.CanPurchase || state.Purchasing,
                HorizontalExpand = true,
                MinHeight = 36,
            };

            button.OnPressed += _ =>
            {
                // Блокируем повторные клики до нового состояния с сервера.
                foreach (var child in VesselsContainer.Children)
                {
                    if (child is BoxContainer box)
                    {
                        foreach (var nested in box.Children)
                        {
                            if (nested is Button b)
                                b.Disabled = true;
                        }
                    }
                }

                OnPurchasePressed?.Invoke(vesselId);
            };

            row.AddChild(button);
            VesselsContainer.AddChild(row);
            VesselsContainer.AddChild(new Control { MinHeight = 4 });
        }
    }
}
