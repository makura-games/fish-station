using Content.Client.UserInterface.Controls;
using Content.Shared._Fish.Xenobiology.Machines;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Fish.Xenobiology.Machines;

[GenerateTypedNameReferences]
public sealed partial class FishXenobiologyConsoleWindow : FancyWindow
{
    public event Action? OnReleaseAll;
    public event Action? OnCollect;
    public event Action? OnScan;
    public event Action? OnFeed;
    public event Action? OnEjectMonkey;
    public event Action? OnRecycle;

    public FishXenobiologyConsoleWindow()
    {
        RobustXamlLoader.Load(this);

        ReleaseButton.OnPressed += _ => OnReleaseAll?.Invoke();
        CollectButton.OnPressed += _ => OnCollect?.Invoke();
        ScanButton.OnPressed += _ => OnScan?.Invoke();
        FeedButton.OnPressed += _ => OnFeed?.Invoke();
        MonkeyButton.OnPressed += _ => OnEjectMonkey?.Invoke();
        RecycleButton.OnPressed += _ => OnRecycle?.Invoke();
    }

    public void UpdateState(FishXenobiologyConsoleBoundUserInterfaceState state)
    {
        StoredLabel.Text = Loc.GetString("fish-xeno-console-stored",
            ("count", state.StoredCount),
            ("max", state.MaxStored));
        CubesLabel.Text = Loc.GetString("fish-xeno-console-cubes", ("count", state.MonkeyCubes));
        PotionLabel.Text = state.LoadedPotionName is { } name
            ? Loc.GetString("fish-xeno-console-potion", ("name", name))
            : Loc.GetString("fish-xeno-console-no-potion-slot");

        StatusLabel.Text = state.StatusMessage ?? Loc.GetString("fish-xeno-console-status-idle");
    }
}
