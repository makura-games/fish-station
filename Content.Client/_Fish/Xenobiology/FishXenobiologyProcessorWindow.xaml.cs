using System.Numerics;
using Content.Client.Stylesheets.Palette;
using Content.Client.UserInterface.Controls;
using Content.Shared._Fish.Xenobiology;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._Fish.Xenobiology;

/// <summary>Compact processor controls reflecting authoritative input and extraction state.</summary>
[GenerateTypedNameReferences]
public sealed partial class FishXenobiologyProcessorWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototype = default!;
    [Dependency] private ILocalizationManager _loc = default!;
    [Dependency] private IEntityManager _entity = default!;
    private FishXenobiologyProcessorBoundUserInterfaceState _state = new();
    private Vector2 _lastViewport;
    private float _elapsed;
    private int _displayedSeconds = -1;
    private bool _awaitingResponse;
    private bool _initialized;

    /// <summary>Requests processing of the existing machine input.</summary>
    public event Action? ProcessRequested;
    /// <summary>Requests release of the existing input, cancelling processing when necessary.</summary>
    public event Action? EjectRequested;

    public FishXenobiologyProcessorWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        HeaderPanel.PanelOverride = FishXenobiologyPresentation.Panel(Palettes.Navy.Background);
        InputPanel.PanelOverride = FishXenobiologyPresentation.Panel(Palettes.Slate.BackgroundDark);
        Progress.ForegroundStyleBoxOverride = FishXenobiologyPresentation.Panel(Palettes.Cyan.Element);
        ProcessButton.OnPressed += _ =>
        {
            if (!_state.CanProcess || _awaitingResponse)
                return;
            AwaitResponse();
            ProcessRequested?.Invoke();
        };
        EjectButton.OnPressed += _ =>
        {
            if (!_state.CanEject || _awaitingResponse)
                return;
            AwaitResponse();
            EjectRequested?.Invoke();
        };
        _initialized = true;
        FitToViewport(UserInterfaceManager.WindowRoot.Size);
        UpdateState(new FishXenobiologyProcessorBoundUserInterfaceState { Status = FishXenobiologyProcessorStatus.Empty });
    }

    /// <summary>Fits the processor to the available logical viewport.</summary>
    public void FitToViewport(Vector2 viewport)
    {
        if (viewport.X <= 0 || viewport.Y <= 0)
            return;
        _lastViewport = UserInterfaceManager.WindowRoot.Size;
        var available = FishXenobiologyPresentation.Available(viewport);
        MinSize = Vector2.Min(new Vector2(360, 320), available);
        MaxSize = available;
        SetSize = Vector2.Min(new Vector2(520, 440), available);
        UpdateButtonLayout();
    }

    protected override void Resized()
    {
        base.Resized();
        if (_initialized)
            UpdateButtonLayout();
    }

    private void UpdateButtonLayout()
    {
        ActionButtons.Orientation = (Size.X > 0 ? Size.X : SetSize.X) < 460
            ? BoxContainer.LayoutOrientation.Vertical : BoxContainer.LayoutOrientation.Horizontal;
    }

    /// <summary>Replaces pending button state with a fresh server response.</summary>
    public void UpdateState(FishXenobiologyProcessorBoundUserInterfaceState state)
    {
        _state = state;
        _elapsed = 0;
        _displayedSeconds = -1;
        _awaitingResponse = false;
        ProcessButton.Disabled = !state.CanProcess;
        EjectButton.Disabled = !state.CanEject;
        ProcessButton.Text = _loc.GetString(state.Processing ? "fish-xeno-processor-processing" : "fish-xeno-process");
        EjectButton.Text = _loc.GetString(state.Processing ? "fish-xeno-cancel-eject" : "fish-xeno-eject");
        Status.SetMessage(_loc.GetString(state.Status switch
        {
            FishXenobiologyProcessorStatus.NoPower => "fish-xeno-processor-no-power",
            FishXenobiologyProcessorStatus.Ready => "fish-xeno-processor-ready",
            FishXenobiologyProcessorStatus.Processing => "fish-xeno-processor-processing",
            FishXenobiologyProcessorStatus.InvalidInput => "fish-xeno-processor-invalid",
            _ => "fish-xeno-processor-idle",
        }), state.Status switch
        {
            FishXenobiologyProcessorStatus.Ready => Palettes.Green.Text,
            FishXenobiologyProcessorStatus.NoPower or FishXenobiologyProcessorStatus.InvalidInput => Palettes.Amber.Text,
            _ => Palettes.Cyan.Text,
        });
        EmptyLabel.Visible = !state.HasInput;
        EmptyInstructions.Visible = !state.HasInput;
        InputPanel.Visible = state.HasInput;
        ProgressPanel.Visible = state.Processing;
        ActionHint.Visible = state.HasInput;
        ActionHint.SetMessage(_loc.GetString(!state.Powered ? "fish-xeno-processor-power-hint" :
            state.Processing ? "fish-xeno-processor-cancel-hint" : state.CanProcess ? "fish-xeno-processor-consume-hint" :
            "fish-xeno-processor-invalid-hint", ("seconds", FishXenobiologyPresentation.Number(state.Duration))), Palettes.Amber.Text);
        if (state.Input is { } input && _prototype.TryIndex<FishXenobiologyBreedPrototype>(input.Breed, out var breed))
        {
            InputName.Text = FishXenobiologyPresentation.Name(input, _loc.GetString(breed.Name), _loc);
            InputName.ToolTip = InputName.Text;
            InputBreed.Text = _loc.GetString(breed.Name);
            InputBreed.ToolTip = InputBreed.Text;
            InputCondition.Text = FishXenobiologyPresentation.Status(input, _loc);
            InputCondition.ToolTip = InputCondition.Text;
            InputCondition.FontColorOverride = FishXenobiologyPresentation.StatusColor(input);
            ExpectedYield.Text = _loc.GetString("fish-xeno-expected-yield", ("count", state.ExpectedYield));
            ExpectedYield.ToolTip = ExpectedYield.Text;
            ExtractIcon.Texture = _entity.System<SpriteSystem>().GetPrototypeIcon(breed.Extract).Default;
            ExtractIcon.Modulate = breed.Color;
            FishXenobiologyPresentation.SetPortrait(Portrait, _entity, breed, input);
        }
        else
        {
            InputName.Text = _loc.GetString("fish-xeno-input-unknown");
            InputName.ToolTip = null;
            InputBreed.Text = string.Empty;
            InputCondition.Text = string.Empty;
            ExpectedYield.Text = string.Empty;
            InputBreed.ToolTip = null;
            InputCondition.ToolTip = null;
            ExpectedYield.ToolTip = null;
            ExtractIcon.Texture = null;
            Portrait.SetPrototype(null);
        }
        UpdateProgress();
    }

    private void AwaitResponse()
    {
        _awaitingResponse = true;
        ProcessButton.Disabled = true;
        EjectButton.Disabled = true;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        var viewport = UserInterfaceManager.WindowRoot.Size;
        if (viewport != _lastViewport)
            FitToViewport(viewport);
        if (!_state.Processing)
            return;
        _elapsed += args.DeltaSeconds;
        UpdateProgress();
    }

    private void UpdateProgress()
    {
        var interpolated = _state.Progress + (_state.Duration > 0 ? _elapsed / _state.Duration : 0);
        Progress.Value = _state.Processing ? Math.Min(FishXenobiologyPresentation.Unit(interpolated), 0.99f) : 0;
        var seconds = (int) MathF.Ceiling(Math.Max(0, _state.SecondsRemaining - _elapsed));
        if (_displayedSeconds == seconds)
            return;
        _displayedSeconds = seconds;
        Remaining.Text = _loc.GetString(seconds == 0 && _state.Processing ? "fish-xeno-processor-finishing" : "fish-xeno-time-remaining", ("seconds", seconds));
    }
}
