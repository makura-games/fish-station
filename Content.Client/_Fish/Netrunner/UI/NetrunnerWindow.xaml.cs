using System.Globalization;
using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Shared._Fish.Netrunner;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Localization;
using Robust.Shared.Utility;

namespace Content.Client._Fish.Netrunner.UI;

/// <summary>Private resource display, camera selection and bounded program journal.</summary>
[GenerateTypedNameReferences]
public sealed partial class NetrunnerWindow : FancyWindow
{
    [Dependency] private ILocalizationManager _loc = default!;

    public event Action<NetEntity>? CameraSelected;
    public event Action? RefreshRequested;
    public event Action? DisconnectRequested;
    public event Action? ShopRequested;
    private List<NetrunnerCameraEntry> _cameras = new();
    private string? _temperatureStyle;

    public NetrunnerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        Cameras.OnItemSelected += args =>
        {
            if (Cameras[args.ItemIndex].Metadata is NetEntity camera)
                CameraSelected?.Invoke(camera);
        };
        Refresh.OnPressed += _ => RefreshRequested?.Invoke();
        Disconnect.OnPressed += _ => DisconnectRequested?.Invoke();
        Shop.OnPressed += _ => ShopRequested?.Invoke();
    }

    public void UpdateState(NetrunnerUiState state)
    {
        DebugStatus.Visible = state.DebugMode;
        var displayRam = MathF.Max(0f, state.Ram);
        RamLabel.Text = _loc.GetString("fish-netrunner-ram", ("ram", Round(displayRam)), ("max", Round(state.MaxRam)));
        RamMeter.MaxValue = MathF.Max(1, MathF.Round(state.MaxRam, 1));
        RamMeter.Value = Math.Clamp(displayRam, 0, RamMeter.MaxValue);
        TraceLabel.Text = _loc.GetString("fish-netrunner-trace", ("trace", Round(state.Trace)));
        TraceMeter.Value = Math.Clamp(state.Trace, 0, 100);
        Resources.Text = _loc.GetString("fish-netrunner-terminal-cooldown", ("seconds", Round(state.Cooldown)));
        Wallet.Text = state.DebugMode ? _loc.GetString("fish-netrunner-wallet-infinite", ("count", state.UnlockedCount))
            : _loc.GetString("fish-netrunner-wallet", ("links", state.NeuralLinks), ("count", state.UnlockedCount));
        Temperature.Text = state.HasBodyTemperature
            ? _loc.GetString("fish-netrunner-temperature", ("temperature", Round(state.BodyTemperature)))
            : _loc.GetString("fish-netrunner-temperature-unavailable");
        var temperatureStyle = !state.HasBodyTemperature || state.BodyTemperature < 40 ? null
            : state.BodyTemperature >= 43 ? StyleClass.StatusCritical : StyleClass.StatusWarning;
        if (_temperatureStyle != temperatureStyle)
        {
            if (_temperatureStyle != null)
                Temperature.RemoveStyleClass(_temperatureStyle);
            if (temperatureStyle != null)
                Temperature.AddStyleClass(temperatureStyle);
            _temperatureStyle = temperatureStyle;
        }
        VisorStatus.Text = _loc.GetString(state.VisorEquipped ? "fish-netrunner-visor-active" : "fish-netrunner-visor-inactive");
        ControlHint.SetMessage(_loc.GetString(state.UnlockedCount == 0 ? "fish-netrunner-empty-hint"
            : state.Connected ? "fish-netrunner-remote-hint" : "fish-netrunner-target-hint"));
        ConnectionStatus.SetMessage(_loc.GetString(state.Connecting ? "fish-netrunner-connecting"
            : state.Connected ? "fish-netrunner-connected" : "fish-netrunner-local"));
        CastStatus.SetMessage(state.CastRemaining > 0
            ? _loc.GetString("fish-netrunner-casting", ("seconds", Round(state.CastRemaining)))
            : string.Empty);
        Disconnect.Disabled = !state.Connected && !state.Connecting;
        var changed = _cameras.Count != state.Cameras.Count;
        for (var i = 0; !changed && i < _cameras.Count; i++)
            changed = _cameras[i] != state.Cameras[i];
        if (changed)
        {
            Cameras.Clear();
            _cameras = state.Cameras;
            foreach (var camera in _cameras)
            {
                Cameras.AddItem(camera.Name, metadata: camera.Entity);
            }
        }
        var entries = new List<string>();
        foreach (var entry in state.Journal)
        {
            entries.Add(_loc.GetString("fish-netrunner-log-entry",
                ("time", $"{(int) entry.Time.TotalHours:00}:{entry.Time.Minutes:00}:{entry.Time.Seconds:00}"),
                ("program", _loc.GetString(entry.Kind.GetLocId())), ("target", FormattedMessage.EscapeText(entry.Target)),
                ("result", _loc.GetString(entry.Success ? "fish-netrunner-log-success" : "fish-netrunner-log-failure"))));
        }
        Journal.SetMessage(string.Join("\n", entries));
    }

    private static string Round(float value)
    {
        var rounded = MathF.Round(value, 1);
        return (rounded == 0f ? 0f : rounded).ToString("0.#", CultureInfo.InvariantCulture);
    }
}
