using System.Globalization;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._Fish.Netrunner;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Localization;
using Robust.Shared.Maths;
using Robust.Shared.Prototypes;

namespace Content.Client._Fish.Netrunner.UI;

/// <summary>Displays the server's catalog and sends explicit purchase requests.</summary>
[GenerateTypedNameReferences]
public sealed partial class NetrunnerShopWindow : FancyWindow
{
    [Dependency] private ILocalizationManager _loc = default!;
    [Dependency] private IPrototypeManager _proto = default!;

    private readonly Dictionary<ProtoId<NetrunnerAbilityPrototype>, ProgramRow> _rows = new();

    public event Action<ProtoId<NetrunnerAbilityPrototype>>? ProgramRequested;
    public event Action<NetrunnerUpgrade>? UpgradeRequested;
    public event Action? VisorRequested;

    public NetrunnerShopWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        EarningHint.SetMessage(_loc.GetString("fish-netrunner-shop-earning"));
        VisorHint.SetMessage(_loc.GetString("fish-netrunner-shop-visor-hint"));
        Memory.OnPressed += _ => UpgradeRequested?.Invoke(NetrunnerUpgrade.Memory);
        Speed.OnPressed += _ => UpgradeRequested?.Invoke(NetrunnerUpgrade.ActivationSpeed);
        Visor.OnPressed += _ => VisorRequested?.Invoke();
        Category.AddItem(_loc.GetString("fish-netrunner-shop-category-all"), (int) ProgramCategory.All);
        Category.AddItem(_loc.GetString("fish-netrunner-shop-category-infrastructure"), (int) ProgramCategory.Infrastructure);
        Category.AddItem(_loc.GetString("fish-netrunner-shop-category-covert"), (int) ProgramCategory.Covert);
        Category.AddItem(_loc.GetString("fish-netrunner-shop-category-combat"), (int) ProgramCategory.Combat);
        Category.OnItemSelected += args =>
        {
            Category.SelectId(args.Id);
            UpdateFilter();
        };
        Search.OnTextChanged += _ => UpdateFilter();
    }

    /// <summary>Updates controls from the authoritative price and ownership snapshot.</summary>
    public void UpdateState(NetrunnerShopState state)
    {
        DebugStatus.Visible = state.DebugMode;
        Balance.Text = state.DebugMode ? _loc.GetString("fish-netrunner-shop-balance-infinite")
            : _loc.GetString("fish-netrunner-shop-balance", ("links", state.NeuralLinks));
        Memory.Text = _loc.GetString("fish-netrunner-shop-memory", ("gain", Round(state.MemoryGain)),
            ("price", state.MemoryPrice));
        Speed.Text = _loc.GetString("fish-netrunner-shop-speed", ("gain", Round(state.SpeedGain * 100)),
            ("price", state.SpeedPrice));
        Memory.Disabled = !state.CanBuy || state.MemoryLevel >= state.MaxMemoryLevel || !state.DebugMode && state.NeuralLinks < state.MemoryPrice;
        Speed.Disabled = !state.CanBuy || state.SpeedLevel >= state.MaxSpeedLevel || !state.DebugMode && state.NeuralLinks < state.SpeedPrice;
        Visor.Text = state.VisorPurchased ? _loc.GetString("fish-netrunner-shop-visor-owned")
            : _loc.GetString("fish-netrunner-shop-visor", ("price", state.VisorPrice));
        Visor.Disabled = state.VisorPurchased || !state.CanBuy || !state.DebugMode && state.NeuralLinks < state.VisorPrice;
        Hardware.SetMessage(_loc.GetString("fish-netrunner-shop-hardware", ("ram", Round(state.MaxRam)),
            ("memory", state.MemoryLevel), ("maxMemory", state.MaxMemoryLevel), ("speed", state.SpeedLevel),
            ("maxSpeed", state.MaxSpeedLevel), ("percent", Round(state.CastMultiplier * 100))));
        foreach (var program in state.Programs)
        {
            if (!_rows.TryGetValue(program.Ability, out var row))
            {
                row = CreateRow(program);
                _rows.Add(program.Ability, row);
            }
            row.Buy.Text = program.Owned ? _loc.GetString("fish-netrunner-shop-owned")
                : _loc.GetString("fish-netrunner-shop-buy", ("price", program.Price));
            row.Buy.Disabled = program.Owned || !state.CanBuy || !state.DebugMode && state.NeuralLinks < program.Price;
            row.Stats.SetMessage(_loc.GetString("fish-netrunner-shop-stats", ("ram", Round(program.RamCost)),
                ("trace", Round(program.TraceCost)), ("cast", Round(program.CastTime)),
                ("cooldown", Round(program.Cooldown))));
        }
        UpdateFilter();
    }

    private ProgramRow CreateRow(NetrunnerShopEntry program)
    {
        var panel = new PanelContainer { HorizontalExpand = true, MinWidth = 280 };
        panel.AddStyleClass(NetrunnerSheetlet.Card);
        var container = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 6 };
        panel.AddChild(container);
        var name = _loc.GetString(program.Kind.GetLocId());
        var category = GetCategory(program.Kind);
        var actionProto = _proto.Index(_proto.Index(program.Ability).Action);
        var headerRow = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 8,
            HorizontalExpand = true,
        };
        var iconView = new EntityPrototypeView
        {
            SetSize = new Vector2(32, 32),
            VerticalAlignment = VAlignment.Center,
        };
        iconView.SetPrototype(actionProto);
        headerRow.AddChild(iconView);

        var headerText = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
        };
        var title = new Label { Text = name, ClipText = true, HorizontalExpand = true };
        title.AddStyleClass(NetrunnerSheetlet.Accent);
        headerText.AddChild(title);
        var categoryLabel = new Label { Text = _loc.GetString(GetCategoryLocId(category)), ClipText = true, HorizontalExpand = true };
        categoryLabel.AddStyleClass(NetrunnerSheetlet.Caption);
        headerText.AddChild(categoryLabel);
        headerRow.AddChild(headerText);
        container.AddChild(headerRow);

        var buy = new Button { HorizontalExpand = true };
        var id = program.Ability;
        buy.OnPressed += _ => ProgramRequested?.Invoke(id);
        var descriptionText = actionProto.Description;
        var description = new RichTextLabel
        {
            HorizontalExpand = true,
            MaxWidth = 290,
            Margin = new Thickness(0, 0, 8, 0),
        };
        description.SetMessage(descriptionText);
        container.AddChild(description);
        var stats = new RichTextLabel
        {
            HorizontalExpand = true,
            MaxWidth = 290,
            Margin = new Thickness(0, 0, 8, 0),
        };
        container.AddChild(stats);
        container.AddChild(buy);
        Programs.AddChild(panel);
        return new ProgramRow(panel, buy, stats, category, name + " " + descriptionText);
    }

    private void UpdateFilter()
    {
        var category = (ProgramCategory) Category.SelectedId;
        var search = Search.Text.Trim();
        var visible = 0;
        foreach (var row in _rows.Values)
        {
            row.Panel.Visible = (category == ProgramCategory.All || row.Category == category)
                && row.SearchText.Contains(search, StringComparison.CurrentCultureIgnoreCase);
            if (row.Panel.Visible)
                visible++;
        }
        EmptySearch.Visible = visible == 0;
    }

    private static ProgramCategory GetCategory(NetrunnerHackKind kind) => kind switch
    {
        NetrunnerHackKind.OpenAirlock or NetrunnerHackKind.LockAirlock or NetrunnerHackKind.DisableCamera
            or NetrunnerHackKind.DisableLight => ProgramCategory.Infrastructure,
        NetrunnerHackKind.DisableSensors or NetrunnerHackKind.DisableHeadset or NetrunnerHackKind.EraseTrace
            => ProgramCategory.Covert,
        _ => ProgramCategory.Combat,
    };

    private static string Round(float value)
    {
        var rounded = MathF.Round(value, 1);
        return (rounded == 0f ? 0f : rounded).ToString("0.#", CultureInfo.InvariantCulture);
    }

    private static LocId GetCategoryLocId(ProgramCategory category) => category switch
    {
        ProgramCategory.Infrastructure => "fish-netrunner-shop-category-infrastructure",
        ProgramCategory.Covert => "fish-netrunner-shop-category-covert",
        ProgramCategory.Combat => "fish-netrunner-shop-category-combat",
        _ => "fish-netrunner-shop-category-all",
    };

    private enum ProgramCategory : byte
    {
        All,
        Infrastructure,
        Covert,
        Combat,
    }

    private sealed record ProgramRow(PanelContainer Panel, Button Buy, RichTextLabel Stats,
        ProgramCategory Category, string SearchText);
}
