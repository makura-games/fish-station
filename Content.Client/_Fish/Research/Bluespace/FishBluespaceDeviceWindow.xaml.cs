using System.Linq;
using System.Numerics;
using Content.Client.Stylesheets;
using Content.Client.Stylesheets.Palette;
using Content.Client.UserInterface.Controls;
using Content.Shared._Fish.Research.Bluespace;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._Fish.Research.Bluespace;

/// <summary>Displays server-authoritative power, station background and production controls.</summary>
[GenerateTypedNameReferences]
public sealed partial class FishBluespaceDeviceWindow : FancyWindow
{
    [Dependency] private ILocalizationManager _loc = default!;
    [Dependency] private IPrototypeManager _prototype = default!;
    [Dependency] private IEntityManager _entity = default!;
    private readonly SpriteSystem _sprite;
    private readonly FishBluespaceHarvesterLootPrototype[] _loot;
    private FishBluespaceDeviceBoundUserInterfaceState? _state;
    private FishBluespaceLootCategory? _previewCategory;
    private FishBluespaceDeviceKind? _kind;
    private Vector2 _lastViewport;
    private bool _initialized;
    private bool _updating;

    /// <summary>Requests a new operating state.</summary>
    public event Action<bool>? EnabledRequested;
    /// <summary>Requests a bounded harvester power mode.</summary>
    public event Action<FishBluespacePowerMode>? PowerModeRequested;
    /// <summary>Requests a configured reward category.</summary>
    public event Action<FishBluespaceLootCategory>? LootCategoryRequested;

    public FishBluespaceDeviceWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sprite = _entity.System<SpriteSystem>();
        _loot = _prototype.EnumeratePrototypes<FishBluespaceHarvesterLootPrototype>().OrderBy(loot => loot.ID).ToArray();
        Progress.ForegroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = Palettes.Cyan.Element };
        foreach (var mode in Enum.GetValues<FishBluespacePowerMode>())
            PowerMode.AddItem(_loc.GetString($"fish-bluespace-mode-{mode.ToString().ToLowerInvariant()}"), (int) mode);
        foreach (var category in Enum.GetValues<FishBluespaceLootCategory>())
            LootCategory.AddItem(_loc.GetString($"fish-bluespace-category-{category.ToString().ToLowerInvariant()}"), (int) category);

        EnableButton.OnPressed += _ =>
        {
            if (_state == null)
                return;
            EnableButton.Disabled = true;
            EnabledRequested?.Invoke(!_state.Enabled);
        };
        PowerMode.OnItemSelected += args =>
        {
            if (!_updating)
                PowerModeRequested?.Invoke((FishBluespacePowerMode) args.Id);
        };
        LootCategory.OnItemSelected += args =>
        {
            if (!_updating)
                LootCategoryRequested?.Invoke((FishBluespaceLootCategory) args.Id);
        };
        InstructionsButton.OnToggled += args => HelpPanel.Visible = args.Pressed;
        _initialized = true;
        FitToViewport(UserInterfaceManager.WindowRoot.Size);
    }

    /// <summary>Fits the device window to the logical viewport, including enlarged UI scales.</summary>
    public void FitToViewport(Vector2 viewport)
    {
        if (viewport.X <= 0 || viewport.Y <= 0)
            return;
        _lastViewport = UserInterfaceManager.WindowRoot.Size;
        var available = Vector2.Max(Vector2.One, viewport - new Vector2(24));
        MinSize = Vector2.Min(new Vector2(560, 450), available);
        MaxSize = available;
        SetSize = Vector2.Min(new Vector2(640, _kind is null or FishBluespaceDeviceKind.Harvester ? 720 : 450), available);
        UpdateLayout();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        var viewport = UserInterfaceManager.WindowRoot.Size;
        if (_lastViewport != viewport)
            FitToViewport(viewport);
    }

    protected override void Resized()
    {
        base.Resized();
        if (_initialized)
            UpdateLayout();
    }

    private void UpdateLayout()
    {
        var width = Size.X > 0 ? Size.X : SetSize.X;
        Metrics.Orientation = width < 520 ? BoxContainer.LayoutOrientation.Vertical : BoxContainer.LayoutOrientation.Horizontal;
        Selectors.Orientation = width < 560 ? BoxContainer.LayoutOrientation.Vertical : BoxContainer.LayoutOrientation.Horizontal;
    }

    /// <summary>Applies a complete device state without generating control requests.</summary>
    public void UpdateState(FishBluespaceDeviceBoundUserInterfaceState state)
    {
        _state = state;
        _updating = true;
        var kind = state.Kind.ToString().ToLowerInvariant();
        Title = DeviceName.Text = _loc.GetString($"fish-bluespace-device-{kind}");
        DeviceName.ToolTip = DeviceName.Text;
        if (_kind != state.Kind)
        {
            _kind = state.Kind;
            Portrait.SetPrototype(state.Kind switch
            {
                FishBluespaceDeviceKind.Harvester => "FishBluespaceHarvester",
                FishBluespaceDeviceKind.Prober => "FishBluespaceProber",
                _ => "FishBluespaceSuppressor",
            });
            Instructions.SetMessage(_loc.GetString($"fish-bluespace-instructions-{kind}"));
            FitToViewport(UserInterfaceManager.WindowRoot.Size);
        }
        Background.Value = FiniteClamp(state.Background, 0, 100);
        BackgroundText.Text = _loc.GetString("fish-bluespace-background-value", ("level", Math.Round((double) Background.Value, 1)));
        var backgroundColor = Palettes.Status.GetStatusColor(1f - Background.Value / 100f);
        Background.ForegroundStyleBoxOverride = new StyleBoxFlat { BackgroundColor = backgroundColor };
        BackgroundText.FontColorOverride = state.Critical ? Palettes.Red.Text : Background.Value >= 85 ? Palettes.Amber.Text : Palettes.Cyan.Text;
        PowerText.SetMessage(_loc.GetString("fish-bluespace-power-value",
            ("received", Math.Round(FiniteClamp(state.ReceivedPower, 0, float.MaxValue) / 1000d, 1)),
            ("requested", Math.Round(FiniteClamp(state.RequestedPower, 0, float.MaxValue) / 1000d, 1))));
        Progress.Value = FiniteClamp(state.Progress, 0, 1);
        ProgressText.Text = state.EnergyPerReward > 0 && float.IsFinite(state.EnergyPerReward)
            ? _loc.GetString("fish-bluespace-energy-value", ("stored", Math.Round((double) Progress.Value * state.EnergyPerReward / 1_000_000d, 1)),
                ("required", Math.Round(state.EnergyPerReward / 1_000_000d, 1)), ("percent", Math.Round(Progress.Value * 100d)))
            : _loc.GetString("fish-bluespace-progress-value", ("percent", Math.Round(Progress.Value * 100d)));
        HarvesterPanel.Visible = state.Kind == FishBluespaceDeviceKind.Harvester;
        EffectPanel.Visible = state.Kind != FishBluespaceDeviceKind.Harvester;
        ResearchRate.Visible = state.Kind == FishBluespaceDeviceKind.Prober;
        var mode = Enum.IsDefined(state.PowerMode) ? state.PowerMode : FishBluespacePowerMode.Normal;
        var category = Enum.IsDefined(state.LootCategory) ? state.LootCategory : FishBluespaceLootCategory.Materials;
        if (PowerMode.SelectedId != (int) mode)
            PowerMode.SelectId((int) mode);
        if (LootCategory.SelectedId != (int) category)
            LootCategory.SelectId((int) category);
        if (state.Kind == FishBluespaceDeviceKind.Harvester && _previewCategory != category)
            BuildPreview(category);
        EnableButton.Text = _loc.GetString(state.Enabled ? "fish-bluespace-disable" : "fish-bluespace-enable");
        EnableButton.Disabled = !state.Enabled && (!state.Anchored || !state.HasStation ||
            state.Critical && state.Kind != FishBluespaceDeviceKind.Suppressor);
        var status = !state.Anchored ? "unanchored" :
            !state.HasStation ? "no-station" :
            state.Critical && state.Kind != FishBluespaceDeviceKind.Suppressor ? "critical" :
            !state.Enabled ? "off" :
            state.Kind == FishBluespaceDeviceKind.Prober && !state.HasResearchServer ? "no-server" :
            !HasWorkingPower(state) ? "no-power" :
            state.OutputBlocked ? "blocked" : "working";
        Status.Text = _loc.GetString($"fish-bluespace-status-{status}");
        ResearchRate.Text = _loc.GetString("fish-bluespace-research-rate",
            ("rate", status == "working" ? Math.Round((double) FiniteClamp(state.PointsPerMinute, 0, float.MaxValue), 1) : 0d));
        Status.ToolTip = Status.Text;
        var color = status == "working" ? Palettes.Green.Text : status == "critical" ? Palettes.Red.Text : Palettes.Amber.Text;
        Status.FontColorOverride = color;
        var hint = status == "working" ? $"fish-bluespace-hint-working-{kind}" : $"fish-bluespace-hint-{status}";
        if (status == "working" && state.Kind == FishBluespaceDeviceKind.Harvester && mode == FishBluespacePowerMode.Overdrive)
            hint = "fish-bluespace-hint-working-harvester-overdrive";
        StatusHint.SetMessage(_loc.GetString(hint), color);
        if (state.Kind != FishBluespaceDeviceKind.Harvester)
            EffectText.SetMessage(_loc.GetString(status == "working" ? $"fish-bluespace-effect-{kind}" : "fish-bluespace-effect-paused"));
        UpdateEta(state, status);
        _updating = false;
    }

    private static bool HasWorkingPower(FishBluespaceDeviceBoundUserInterfaceState state)
    {
        if (!state.Powered || !float.IsFinite(state.ReceivedPower) || !float.IsFinite(state.RequestedPower) ||
            state.RequestedPower <= 0 || state.ReceivedPower <= 0)
            return false;
        return state.Kind == FishBluespaceDeviceKind.Harvester || state.ReceivedPower >= state.RequestedPower * 0.99f;
    }

    private void UpdateEta(FishBluespaceDeviceBoundUserInterfaceState state, string status)
    {
        if (state.Kind != FishBluespaceDeviceKind.Harvester || status != "working" ||
            !float.IsFinite(state.EnergyPerReward) || state.EnergyPerReward <= 0)
        {
            Eta.SetMessage(_loc.GetString("fish-bluespace-eta-paused"));
            return;
        }
        var power = Math.Min(state.ReceivedPower, state.RequestedPower);
        var seconds = Math.Ceiling((1d - Progress.Value) * state.EnergyPerReward / power);
        Eta.SetMessage(_loc.GetString(seconds <= 0 ? "fish-bluespace-eta-ready" : "fish-bluespace-eta-value", ("seconds", seconds)));
    }

    private void BuildPreview(FishBluespaceLootCategory category)
    {
        _previewCategory = category;
        LootPreview.RemoveAllChildren();
        var choices = _loot.Where(loot => loot.Category == category && float.IsFinite(loot.Weight) && loot.Weight > 0 &&
            loot.Products.Count > 0 && loot.Products.Values.All(count => count > 0)).ToArray();
        var total = choices.Sum(loot => (double) loot.Weight);
        PreviewHeading.Text = _loc.GetString("fish-bluespace-preview-title", ("count", choices.Length));
        foreach (var choice in choices)
        {
            var panel = new PanelContainer { StyleClasses = { StyleClass.PanelInsetDark } };
            var contents = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 4, Margin = new Thickness(8), HorizontalExpand = true };
            contents.AddChild(new Label { Text = _loc.GetString("fish-bluespace-preview-chance", ("chance", Math.Round(choice.Weight / total * 100d, 1))),
                StyleClasses = { StyleClass.LabelSubText } });
            foreach (var (product, count) in choice.Products)
            {
                var row = new BoxContainer { SeparationOverride = 8, HorizontalExpand = true };
                row.AddChild(new TextureRect
                {
                    Texture = _sprite.GetPrototypeIcon(product).Default,
                    SetSize = new Vector2(32),
                    Stretch = TextureRect.StretchMode.KeepAspectCentered,
                });
                var name = _loc.GetString("fish-bluespace-preview-product", ("count", count), ("name", _prototype.Index(product).Name));
                var label = new RichTextLabel { HorizontalExpand = true, VerticalAlignment = VAlignment.Center };
                label.SetMessage(FormattedMessage.FromUnformatted(name));
                row.AddChild(label);
                contents.AddChild(row);
            }
            panel.AddChild(contents);
            LootPreview.AddChild(panel);
        }
    }

    private static float FiniteClamp(float value, float min, float max)
    {
        return float.IsFinite(value) ? Math.Clamp(value, min, max) : min;
    }
}
