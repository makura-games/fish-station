using System.Numerics;
using Content.Shared.Research.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Fish.Research.UI;

[GenerateTypedNameReferences]
public sealed partial class FishTechnologyCard : PanelContainer
{
    private readonly TechnologyPrototype _technology;

    internal FishTechnologyCard(TechnologyPrototype technology, TechDisciplinePrototype discipline, SpriteSystem sprites,
        IReadOnlyList<FishResearchUnlock> unlocks, Action<string> research)
    {
        RobustXamlLoader.Load(this);
        _technology = technology;
        TitleLabel.SetMessage(Loc.GetString(technology.Name));
        Icon.Texture = sprites.Frame0(technology.Icon);
        Stripe.ModulateSelfOverride = discipline.Color;
        TierLabel.SetMessage(FormattedMessage.FromMarkupOrThrow(Loc.GetString("research-console-tier-discipline-info",
            ("tier", technology.Tier), ("color", discipline.Color), ("discipline", Loc.GetString(discipline.Name)))));
        Price.Text = Loc.GetString("fish-rnd-price", ("points", technology.Cost));

        const int maxPreview = 4;
        for (var i = 0; i < Math.Min(maxPreview, unlocks.Count); i++)
        {
            var unlock = unlocks[i];
            var name = unlock.Name;
            if (unlock.GetIcon(sprites) is { } texture)
                Preview.AddChild(new TextureRect
                {
                    Texture = texture, SetSize = new Vector2(32), CanShrink = true,
                    Stretch = TextureRect.StretchMode.KeepAspectCentered, ToolTip = name, MouseFilter = MouseFilterMode.Stop,
                });
            else
                Preview.AddChild(new Label { Text = name, ClipText = true, HorizontalExpand = true, ToolTip = name });
        }

        if (unlocks.Count > maxPreview)
            Preview.AddChild(new Label { Text = $"+{unlocks.Count - maxPreview}" });
        ResearchButton.OnPressed += _ => research(technology.ID);
    }

    public void UpdatePurchase(int points, bool access)
    {
        var missing = _technology.Cost - points;
        ResearchButton.Disabled = !access || missing > 0;
        ResearchButton.Text = !access ? Loc.GetString("research-console-no-access-popup") :
            missing > 0 ? Loc.GetString("fish-rnd-shortfall", ("points", missing)) :
            Loc.GetString("research-console-menu-server-research-button");
        ResearchButton.ModulateSelfOverride = ResearchButton.Disabled ? null : Color.FromHex("#73DEC4");
    }
}

internal sealed record FishResearchUnlock(string Name, LatheRecipePrototype? Recipe = null, string? ProductName = null)
{
    public Texture? GetIcon(SpriteSystem sprites)
    {
        if (Recipe?.Icon is { } icon)
            return sprites.Frame0(icon);

        return Recipe?.Result is { } result ? sprites.GetPrototypeIcon(result).Default : null;
    }
}
