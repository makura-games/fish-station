namespace Content.Client._Fish.Research.UI;

[GenerateTypedNameReferences]
public sealed partial class FishResearchWindow : FancyWindow
{
    [Dependency] private IEntityManager _entities = default!;
    [Dependency] private IPrototypeManager _prototypes = default!;
    [Dependency] private IPlayerManager _players = default!;
    private readonly ResearchSystem _research;
    private readonly SpriteSystem _sprites;
    private readonly LatheSystem _lathe;
    private readonly List<FishTechnologyCard> _cards = new();
    private readonly List<Entry> _catalog = new();
    private string? _selected;
    private string[] _offers = [];
    private ProtoId<TechnologyPrototype>[] _unlocked = [];
    private ProtoId<TechDisciplinePrototype>[] _disciplines = [];
    private ProtoId<TechDisciplinePrototype>? _main;
    private bool _initialized;

    public event Action<string>? OnTechnologyCardPressed;
    public event Action? OnServerButtonPressed;

    private sealed record Entry(TechnologyPrototype Tech, string Name, LocId Status,
        List<FishResearchUnlock> Unlocks);

    public FishResearchWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _research = _entities.System<ResearchSystem>();
        _sprites = _entities.System<SpriteSystem>();
        _lathe = _entities.System<LatheSystem>();
        StudyTab.Group = new ButtonGroup(isNoneSetAllowed: false);
        CatalogTab.Group = StudyTab.Group;
        StudyTab.OnPressed += _ => SelectTab(0);
        CatalogTab.OnPressed += _ => SelectTab(1);
        SelectTab(0);
        ServerButton.OnPressed += _ => OnServerButtonPressed?.Invoke();
        Search.OnTextChanged += _ => FilterCatalog();
        Results.OnItemSelected += args => ShowDetails((Entry) Results[args.ItemIndex].Metadata!);
    }

    private void SelectTab(int index)
    {
        Tabs.CurrentTab = index;
        var accent = Color.FromHex("#C19AE8");
        StudyTab.ModulateSelfOverride = index == 0 ? accent : null;
        CatalogTab.ModulateSelfOverride = index == 1 ? accent : null;
    }

    public void Refresh(EntityUid console, ResearchConsoleBoundInterfaceState state, bool force = false)
    {
        Balance.Text = Loc.GetString("fish-rnd-balance", ("points", state.Points));
        _entities.TryGetComponent<TechnologyDatabaseComponent>(console, out var db);
        if (force || !_initialized || !_offers.SequenceEqual(db?.CurrentTechnologyCards ?? [])
            || !_unlocked.SequenceEqual(db?.UnlockedTechnologies ?? [])
            || !_disciplines.SequenceEqual(db?.SupportedDisciplines ?? []) || _main != db?.MainDiscipline)
        {
            _initialized = true;
            _offers = db == null ? [] : [.. db.CurrentTechnologyCards];
            _unlocked = db == null ? [] : [.. db.UnlockedTechnologies];
            _disciplines = db == null ? [] : [.. db.SupportedDisciplines];
            _main = db?.MainDiscipline;
            Rebuild(console, db);
        }

        var access = _players.LocalEntity is not { } player ||
            !_entities.TryGetComponent<AccessReaderComponent>(console, out var reader) ||
            _entities.System<AccessReaderSystem>().IsAllowed(player, console, reader);
        foreach (var card in _cards)
            card.UpdatePurchase(state.Points, access);
    }

    private void Rebuild(EntityUid console, TechnologyDatabaseComponent? db)
    {
        CardRows.Children.Clear();
        TierDisplay.Children.Clear();
        _cards.Clear();
        _catalog.Clear();
        var discipline = _main is { } id ? _prototypes.Index(id) : null;
        MainDisciplineLabel.SetMessage(FormattedMessage.FromMarkupOrThrow(Loc.GetString("research-console-menu-main-discipline",
            ("name", Loc.GetString(discipline?.Name ?? "research-discipline-none")),
            ("color", discipline?.Color ?? Color.Gray))));
        EmptyOffers.Visible = _offers.Length == 0;
        if (db != null)
        {
            foreach (var (key, tier) in _research.GetDisciplineTiers(db))
            {
                if (tier == 0)
                    continue;
                var proto = _prototypes.Index<TechDisciplinePrototype>(key);
                TierDisplay.AddChild(new TextureRect
                {
                    Texture = _sprites.Frame0(proto.Icon), SetSize = new Vector2(18), CanShrink = true,
                    Stretch = TextureRect.StretchMode.KeepAspectCentered, ToolTip = Loc.GetString(proto.Name),
                    MouseFilter = MouseFilterMode.Stop,
                });
                TierDisplay.AddChild(new Label { Text = tier.ToString() });
            }

            var technologies = _research.GetAvailableTechnologies(console, db)
                .Concat(_offers.Select(key => _prototypes.Index<TechnologyPrototype>(key)))
                .Concat(_unlocked.Select(key => _prototypes.Index(key))).DistinctBy(tech => tech.ID);
            foreach (var tech in technologies)
            {
                LocId status = _unlocked.Contains(tech.ID) ? "fish-rnd-studied" :
                    _offers.Contains(tech.ID) ? "fish-rnd-offered" : "fish-rnd-in-pool";
                var unlocks = new List<FishResearchUnlock>();
                foreach (var recipeId in tech.RecipeUnlocks)
                {
                    var recipe = _prototypes.Index(recipeId);
                    var productName = recipe.Name != null && recipe.Result is { } product
                        ? _prototypes.Index(product).Name : null;
                    unlocks.Add(new FishResearchUnlock(_lathe.GetRecipeName(recipe), recipe, productName));
                }
                foreach (var effect in tech.GenericUnlocks)
                    unlocks.Add(new FishResearchUnlock(Loc.GetString(effect.UnlockDescription)));
                _catalog.Add(new Entry(tech, Loc.GetString(tech.Name), status, unlocks));
            }

            BoxContainer row = default!;
            foreach (var key in _offers)
            {
                if (_cards.Count % 2 == 0)
                {
                    row = new BoxContainer { SeparationOverride = 8 };
                    CardRows.AddChild(row);
                }
                var entry = _catalog.First(item => item.Tech.ID == key);
                var card = new FishTechnologyCard(entry.Tech, _prototypes.Index(entry.Tech.Discipline), _sprites,
                    entry.Unlocks, tech => OnTechnologyCardPressed?.Invoke(tech));
                _cards.Add(card);
                row.AddChild(card);
            }
            if (_cards.Count % 2 == 1)
                row.AddChild(new Control { HorizontalExpand = true });
        }

        _catalog.Sort((a, b) => StringComparer.CurrentCultureIgnoreCase.Compare(a.Name, b.Name));
        FilterCatalog();
    }

    private void FilterCatalog()
    {
        Results.Clear();
        var query = Search.Text.Trim();
        ItemList.Item? selection = null;
        foreach (var entry in _catalog)
        {
            if (!entry.Name.Contains(query, StringComparison.CurrentCultureIgnoreCase) &&
                !entry.Unlocks.Any(item => item.Name.Contains(query, StringComparison.CurrentCultureIgnoreCase) ||
                    item.ProductName?.Contains(query, StringComparison.CurrentCultureIgnoreCase) == true))
                continue;
            var item = Results.AddItem(entry.Name, metadata: entry);
            if (entry.Tech.ID == _selected)
                selection = item;
        }
        if (Results.Count != 0)
        {
            (selection ?? Results[0]).Selected = true;
            return;
        }
        Details.Children.Clear();
        Details.AddChild(new Label { Text = Loc.GetString("fish-rnd-no-results") });
    }

    private void ShowDetails(Entry entry)
    {
        _selected = entry.Tech.ID;
        Details.Children.Clear();
        AddText(Details, entry.Name, "LabelHeading");
        Details.AddChild(new TextureRect
        {
            Texture = _sprites.Frame0(entry.Tech.Icon), SetSize = new Vector2(96), CanShrink = true,
            Stretch = TextureRect.StretchMode.KeepAspectCentered, HorizontalAlignment = HAlignment.Center,
        });
        var discipline = _prototypes.Index(entry.Tech.Discipline);
        var tier = new RichTextLabel();
        tier.SetMessage(FormattedMessage.FromMarkupOrThrow(Loc.GetString("research-console-tier-discipline-info", ("tier", entry.Tech.Tier),
            ("color", discipline.Color), ("discipline", Loc.GetString(discipline.Name)))));
        Details.AddChild(tier);
        AddText(Details, Loc.GetString("fish-rnd-price", ("points", entry.Tech.Cost)));
        AddText(Details, Loc.GetString(entry.Status), "LabelKeyText");
        if (entry.Tech.TechnologyPrerequisites.Count != 0)
        {
            AddText(Details, Loc.GetString("research-console-prereqs-list-start"), "LabelKeyText");
            foreach (var prerequisite in entry.Tech.TechnologyPrerequisites)
                AddText(Details, Loc.GetString(_prototypes.Index(prerequisite).Name));
        }
        if (entry.Unlocks.Count != 0)
            AddText(Details, Loc.GetString("research-console-unlocks-list-start"), "LabelKeyText");
        foreach (var unlock in entry.Unlocks)
        {
            var row = new BoxContainer { SeparationOverride = 6 };
            if (unlock.GetIcon(_sprites) is { } icon)
                row.AddChild(new TextureRect
                {
                    Texture = icon, SetSize = new Vector2(32), CanShrink = true,
                    Stretch = TextureRect.StretchMode.KeepAspectCentered,
                });
            AddText(row, unlock.Name);
            Details.AddChild(row);
        }
    }

    private static void AddText(BoxContainer parent, string text, string? style = null)
    {
        var label = new RichTextLabel { HorizontalExpand = true, VerticalAlignment = VAlignment.Center };
        if (style != null)
            label.AddStyleClass(style);
        label.SetMessage(text);
        parent.AddChild(label);
    }
}
