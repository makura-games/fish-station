/// <summary>
/// Presents the existing research console rules as a browsable technology tree.
/// The server remains authoritative for research availability, prices and purchases.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class FishResearchConsoleMenu : FancyWindow
{
    [Dependency] private IEntityManager _entity = default!;
    [Dependency] private IPrototypeManager _prototype = default!;
    [Dependency] private IPlayerManager _player = default!;
    [Dependency] private ILocalizationManager _loc = default!;

    private readonly ResearchSystem _research;
    private readonly SpriteSystem _sprite;
    private readonly AccessReaderSystem _accessReader;
    private readonly SharedLatheSystem _lathe;
    private readonly Dictionary<ProtoId<TechnologyPrototype>, FishResearchNodeState> _nodeStates = new();
    private readonly HashSet<ProtoId<TechDisciplinePrototype>> _supported = new();
    private readonly HashSet<ProtoId<TechnologyPrototype>> _unlocked = new();
    private readonly Dictionary<ProtoId<TechDisciplinePrototype>, Button> _disciplineButtons = new();
    private readonly Dictionary<ProtoId<TechDisciplinePrototype>, RichTextLabel> _disciplineProgress = new();
    private FishResearchTreeCatalog? _catalog;
    private ProtoId<TechDisciplinePrototype>? _filterDiscipline;
    private Button? _allDisciplinesButton;
    private EntityUid _console;
    private int _points;
    private bool _hasAccess;
    private bool _forceRefresh = true;
    private bool _detailsDirty = true;
    private bool _centerAfterNavigation;

    /// <summary>Requests an existing console purchase message for an available technology.</summary>
    public event Action<string>? OnTechnologyCardPressed;

    /// <summary>Requests the existing server selection interface.</summary>
    public event Action? OnServerButtonPressed;

    /// <summary>The selected technology, preserved across ordinary console updates.</summary>
    public ProtoId<TechnologyPrototype>? SelectedTechnology => Graph.SelectedTechnology;

    public FishResearchConsoleMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _research = _entity.System<ResearchSystem>();
        _sprite = _entity.System<SpriteSystem>();
        _accessReader = _entity.System<AccessReaderSystem>();
        _lathe = _entity.System<SharedLatheSystem>();

        HeaderPanel.PanelOverride = PanelStyle(Palettes.Navy.Background);
        SidebarPanel.PanelOverride = PanelStyle(Palettes.Slate.Background);
        GraphPanel.PanelOverride = PanelStyle(Palettes.Slate.BackgroundDark);
        DetailsPanel.PanelOverride = PanelStyle(Palettes.Navy.BackgroundDark);
        FooterPanel.PanelOverride = PanelStyle(Palettes.Slate.Background);
        ResearchedLegend.FontColorOverride = FishResearchTreeControl.StateColor(FishResearchNodeState.Researched);
        AvailableLegend.FontColorOverride = FishResearchTreeControl.StateColor(FishResearchNodeState.Available);
        LockedLegend.FontColorOverride = FishResearchTreeControl.StateColor(FishResearchNodeState.Locked);
        NavigationHint.ToolTip = _loc.GetString("fish-research-tree-navigation");
        FreeChoiceHint.ToolTip = _loc.GetString("fish-research-tree-free-choice");
        ZoomInButton.ToolTip = _loc.GetString("fish-research-tree-zoom-in");
        ZoomOutButton.ToolTip = _loc.GetString("fish-research-tree-zoom-out");

        var available = UserInterfaceManager.WindowRoot.Size - new Vector2(24);
        if (available.X > 0 && available.Y > 0)
        {
            MinSize = Vector2.Min(new Vector2(800, 480), available);
            SetSize = Vector2.Min(new Vector2(1100, 700), available);
            if (available.X < 820)
            {
                SidebarPanel.Visible = false;
                SidebarButton.Pressed = false;
                DetailsPanel.SetWidth = 230;
            }
        }

        ServerButton.OnPressed += _ => OnServerButtonPressed?.Invoke();
        ResearchButton.OnPressed += _ => TryResearchSelected();
        SearchEdit.OnTextChanged += _ => ApplyFilter();
        SidebarButton.OnToggled += args => SidebarPanel.Visible = args.Pressed;
        CenterButton.OnPressed += _ => Graph.CenterSelection();
        ZoomInButton.OnPressed += _ => Graph.ZoomAt(1.12f, Graph.Size / 2);
        ZoomOutButton.OnPressed += _ => Graph.ZoomAt(1 / 1.12f, Graph.Size / 2);
        ResetButton.OnPressed += _ =>
        {
            Graph.SetViewport(0.8f, new Vector2(20, 20));
            Graph.CenterSelection();
        };
        Graph.OnTechnologySelected += _ =>
        {
            _detailsDirty = true;
            RefreshDetails();
        };
        Graph.OnViewChanged += UpdateViewLabels;
        RefreshDetails();
        UpdateViewLabels();
    }

    protected override Vector2 ArrangeOverride(Vector2 finalSize)
    {
        var size = base.ArrangeOverride(finalSize);
        if (_centerAfterNavigation && TreeContent.Visible)
        {
            _centerAfterNavigation = false;
            Graph.CenterSelection();
        }

        return size;
    }

    private static StyleBoxFlat PanelStyle(Color background) => new()
    {
        BackgroundColor = background,
        BorderColor = Palettes.Slate.Element,
        BorderThickness = new Thickness(1),
    };

    /// <summary>Binds the window to the console's existing networked technology database.</summary>
    public void SetEntity(EntityUid entity)
    {
        _console = entity;
        _forceRefresh = true;
    }

    /// <summary>Updates node states while retaining catalog, filter, selection, pan and zoom.</summary>
    public void UpdatePanels(ResearchConsoleBoundInterfaceState state)
    {
        _points = state.Points;
        if (!_entity.TryGetComponent(_console, out TechnologyDatabaseComponent? database))
        {
            ResearchButton.Disabled = true;
            PurchaseStatusLabel.SetMessage(_loc.GetString("fish-research-tree-no-database"));
            return;
        }

        var catalogChanged = _forceRefresh || _catalog == null || !_supported.SetEquals(database.SupportedDisciplines);
        if (catalogChanged)
        {
            _supported.Clear();
            _supported.UnionWith(database.SupportedDisciplines);
            _catalog = new FishResearchTreeCatalog(_prototype, _loc, _sprite, _lathe, database.SupportedDisciplines);
            Graph.SetCatalog(_catalog, _loc);
            BuildDisciplineList();
            _forceRefresh = false;
        }

        var progressChanged = catalogChanged || !_unlocked.SetEquals(database.UnlockedTechnologies);
        _unlocked.Clear();
        _unlocked.UnionWith(database.UnlockedTechnologies);
        _hasAccess = HasConsoleAccess();

        var catalog = _catalog!;
        var disciplineTiers = _research.GetDisciplineTiers(database);
        _nodeStates.Clear();
        foreach (var (id, technology) in catalog.Technologies)
        {
            var nodeState = _unlocked.Contains(id)
                ? FishResearchNodeState.Researched
                : !_research.IsTechnologyAvailable(database, technology.Prototype, disciplineTiers)
                    ? FishResearchNodeState.Locked
                    : FishResearchNodeState.Available;
            _nodeStates.Add(id, nodeState);
        }
        Graph.UpdateStates(_nodeStates);

        if (progressChanged)
            UpdateDisciplineProgress();

        if (SelectedTechnology == null)
        {
            var initial = catalog.Technologies.Keys.FirstOrDefault(id => _nodeStates[id] == FishResearchNodeState.Available);
            if (initial == default)
                initial = catalog.Technologies.Keys.FirstOrDefault();
            if (initial != default)
            {
                Graph.SelectTechnology(initial);
                Graph.CenterSelection();
            }
        }

        _detailsDirty |= catalogChanged || progressChanged;
        RefreshDetails();
    }

    /// <summary>Refreshes the research point balance and purchase availability.</summary>
    public void UpdateInformationPanel(ResearchConsoleBoundInterfaceState state)
    {
        _points = state.Points;
        PointsLabel.Text = _loc.GetString("fish-research-tree-points", ("points", state.Points));
        UpdatePurchaseStatus();
    }

    /// <summary>Rebuilds cached prototype presentation after relevant hot reloads.</summary>
    public void OnProtoReload(PrototypesReloadedEventArgs args)
    {
        if (!args.WasModified<TechnologyPrototype>() && !args.WasModified<TechDisciplinePrototype>() &&
            !args.WasModified<LatheRecipePrototype>() && !args.WasModified<EntityPrototype>())
            return;

        _forceRefresh = true;
        UpdatePanels(new ResearchConsoleBoundInterfaceState(_points));
        UpdateInformationPanel(new ResearchConsoleBoundInterfaceState(_points));
    }

    /// <summary>Selects a technology in the catalog without purchasing it.</summary>
    public bool SelectTechnology(ProtoId<TechnologyPrototype> id) => Graph.SelectTechnology(id);

    private bool HasConsoleAccess()
    {
        if (_player.LocalEntity is not { } local ||
            !_entity.TryGetComponent<AccessReaderComponent>(_console, out var access) || !access.Enabled)
            return true;

        // Fish-edit: обновление прав в дереве не создаёт записи в журнале доступа.
        var items = _accessReader.FindPotentialAccessItems(local);
        var tags = _accessReader.FindAccessTags(local, items);
        _accessReader.FindStationRecordKeys(local, out var keys, items);
        return _accessReader.IsAllowed(tags, keys, _console, access);
    }

    private void TryResearchSelected()
    {
        if (SelectedTechnology is not { } id || _catalog == null || !_catalog.Technologies.TryGetValue(id, out var technology) ||
            !_entity.TryGetComponent(_console, out TechnologyDatabaseComponent? database))
            return;

        if (_points < technology.Prototype.Cost ||
            !HasConsoleAccess() || !_research.IsTechnologyAvailable(database, technology.Prototype))
            return;

        OnTechnologyCardPressed?.Invoke(technology.Prototype.ID);
    }

    private void BuildDisciplineList()
    {
        DisciplineList.RemoveAllChildren();
        _disciplineButtons.Clear();
        _disciplineProgress.Clear();
        var allName = _loc.GetString("fish-research-tree-all");
        _allDisciplinesButton = new Button { Text = allName, ToolTip = allName, ToggleMode = true, ClipText = true };
        StyleDisciplineButton(_allDisciplinesButton);
        _allDisciplinesButton.OnPressed += _ => SetDiscipline(null);
        DisciplineList.AddChild(_allDisciplinesButton);

        if (_catalog == null)
            return;
        if (_filterDiscipline is { } filter && !_catalog.Disciplines.ContainsKey(filter))
            _filterDiscipline = null;

        foreach (var (id, discipline) in _catalog.Disciplines)
        {
            var group = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 3 };
            var name = _loc.GetString(discipline.Name);
            var button = new Button { Text = name, ToolTip = name, ToggleMode = true, ClipText = true, HorizontalExpand = true };
            StyleDisciplineButton(button);
            button.OnPressed += _ => SetDiscipline(id);
            var heading = new BoxContainer { SeparationOverride = 6, HorizontalExpand = true };
            heading.AddChild(new TextureRect
            {
                Texture = _catalog.DisciplineIcons[id],
                SetSize = new(24, 24),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                VerticalAlignment = VAlignment.Center,
                ModulateSelfOverride = discipline.Color,
            });
            heading.AddChild(button);
            group.AddChild(heading);
            var progress = new RichTextLabel { HorizontalExpand = true };
            group.AddChild(progress);
            DisciplineList.AddChild(group);
            _disciplineButtons.Add(id, button);
            _disciplineProgress.Add(id, progress);
        }
        UpdateDisciplineButtons();
        Graph.SetFilter(_filterDiscipline, SearchEdit.Text);
    }

    private static void StyleDisciplineButton(Button button)
    {
        button.TextAlign = Label.AlignMode.Left;
        // Fish-edit: нативный класс Label принудительно центрирует текст поверх TextAlign.
        button.Label.RemoveStyleClass(Button.StyleClassButton);
        button.Label.AddStyleClass(StyleClass.FontSmall);
    }

    private void SetDiscipline(ProtoId<TechDisciplinePrototype>? discipline)
    {
        _filterDiscipline = discipline;
        UpdateDisciplineButtons();
        ApplyFilter();
    }

    private void UpdateDisciplineButtons()
    {
        if (_allDisciplinesButton != null)
            _allDisciplinesButton.Pressed = _filterDiscipline == null;
        foreach (var (id, button) in _disciplineButtons)
            button.Pressed = _filterDiscipline == id;
    }

    private void ApplyFilter()
    {
        Graph.SetFilter(_filterDiscipline, SearchEdit.Text);
        if (SelectedTechnology is { } selected && Graph.VisibleTechnologyIds.Contains(selected))
            Graph.CenterSelection();
        else if (Graph.VisibleTechnologyIds.FirstOrDefault() is var first && first != default)
        {
            Graph.SelectTechnology(first);
            Graph.CenterSelection();
        }
        UpdateViewLabels();
    }

    private void NavigateToTechnology(ProtoId<TechnologyPrototype> id)
    {
        if (_catalog == null || !_catalog.Technologies.ContainsKey(id))
            return;

        if (!Graph.VisibleTechnologyIds.Contains(id))
        {
            SearchEdit.Text = string.Empty;
            SetDiscipline(null);
        }
        Graph.SelectTechnology(id);
        // Fish-start: после смены фильтра центрируем дерево с актуальным размером раскладки.
        _centerAfterNavigation = true;
        InvalidateArrange();
        // Fish-end
    }

    private void UpdateViewLabels()
    {
        ZoomLabel.Text = _loc.GetString("fish-research-tree-zoom", ("percent", MathF.Round(Graph.Zoom * 100)));
        ResultCountLabel.Text = _loc.GetString("fish-research-tree-visible", ("count", Graph.VisibleTechnologyIds.Count), ("total", _catalog?.Technologies.Count ?? 0));
        ResultCountLabel.ToolTip = ResultCountLabel.Text;
    }

    private void UpdateDisciplineProgress()
    {
        if (_catalog == null)
            return;
        foreach (var (id, label) in _disciplineProgress)
        {
            var technologies = _catalog.Technologies.Values.Where(technology => technology.Prototype.Discipline == id).ToArray();
            var lines = new List<string>();
            foreach (var tier in technologies.Select(technology => technology.Prototype.Tier).Distinct().Order())
            {
                var tierTechnologies = technologies.Where(technology => technology.Prototype.Tier == tier).ToArray();
                var count = tierTechnologies.Count(technology => _unlocked.Contains(technology.Prototype.ID));
                lines.Add(_loc.GetString("fish-research-tree-tier-progress", ("tier", tier), ("unlocked", count), ("total", tierTechnologies.Length)));
            }
            label.SetMessage(string.Join('\n', lines));
        }
    }
}
