using System.Text;
using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Shared._Fish.Skills;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Fish.Skills;

/// <summary>
/// Компактное меню навыков в духе Bay/SS1984: категория, имя, шкала уровня, ±.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SkillWindow : FancyWindow
{
    public event Action<string>? OnIncrease;
    public event Action<string>? OnDecrease;
    public event Action? OnConfirm;
    public event Action? OnReset;

    private readonly Dictionary<string, int> _levels = new();

    public SkillWindow()
    {
        RobustXamlLoader.Load(this);
        ConfirmButton.OnPressed += _ => OnConfirm?.Invoke();
        ResetButton.OnPressed += _ => OnReset?.Invoke();
    }

    public int GetLevel(string skillId) => _levels.GetValueOrDefault(skillId, SkillLevels.Unskilled);

    public void UpdateState(SkillEuiState state)
    {
        HeaderLabel.Text = state.JobName != null
            ? Loc.GetString("skills-window-header-job", ("job", state.JobName))
            : Loc.GetString("skills-window-header");

        PointsLabel.Text = Loc.GetString("skills-window-points-value",
            ("remaining", state.RemainingPoints),
            ("total", state.TotalPoints));

        if (!string.IsNullOrWhiteSpace(state.StatusMessage))
        {
            StatusLabel.Visible = true;
            StatusLabel.Text = state.StatusMessage;
        }
        else
        {
            StatusLabel.Visible = false;
        }

        LockedHintLabel.Visible = state.Locked;
        if (state.Locked)
            LockedHintLabel.Text = Loc.GetString("skills-window-locked-hint");

        ConfirmButton.Disabled = state.Locked;
        ResetButton.Disabled = state.Locked;

        SkillsContainer.RemoveAllChildren();
        _levels.Clear();

        if (state.Skills.Count == 0)
        {
            SkillsContainer.AddChild(new Label
            {
                Text = Loc.GetString("skills-error-no-skillset"),
                Align = Label.AlignMode.Center,
            });
            return;
        }

        string? lastCategory = null;
        foreach (var skill in state.Skills)
        {
            if (lastCategory != skill.Category)
            {
                lastCategory = skill.Category;
                SkillsContainer.AddChild(new Label
                {
                    Text = Loc.GetString("skills-category-" + skill.Category),
                    StyleClasses = { "LabelHeading" },
                    Margin = new Thickness(0, 8, 0, 2),
                });
            }

            _levels[skill.SkillId] = skill.CurrentLevel;
            SkillsContainer.AddChild(BuildSkillRow(skill));
        }
    }

    private Control BuildSkillRow(SkillUiEntry skill)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 1,
            Margin = new Thickness(0, 0, 0, 4),
        };

        var top = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 8,
        };

        top.AddChild(new Label
        {
            Text = skill.Name,
            MinWidth = 160,
            HorizontalExpand = true,
            StyleClasses = { "LabelKeyText" },
        });

        top.AddChild(new Label
        {
            Text = FormatLevelBar(skill.CurrentLevel, skill.MaxLevel),
            MinWidth = 90,
            Align = Label.AlignMode.Center,
        });

        top.AddChild(new Label
        {
            Text = Loc.GetString(SkillLevels.GetLevelNameKey(skill.CurrentLevel)),
            MinWidth = 100,
        });

        var dec = new Button
        {
            Text = "−",
            Disabled = !skill.CanDecrease,
            MinWidth = 36,
            ToolTip = Loc.GetString("skills-window-decrease"),
        };
        var skillId = skill.SkillId;
        dec.OnPressed += _ => OnDecrease?.Invoke(skillId);

        var inc = new Button
        {
            Text = skill.NextLevelCost > 0
                ? Loc.GetString("skills-window-increase-cost", ("cost", skill.NextLevelCost))
                : "+",
            Disabled = !skill.CanIncrease,
            MinWidth = 64,
            ToolTip = Loc.GetString("skills-window-increase"),
        };
        inc.OnPressed += _ => OnIncrease?.Invoke(skillId);

        top.AddChild(dec);
        top.AddChild(inc);
        row.AddChild(top);

        if (!string.IsNullOrWhiteSpace(skill.EffectHint))
        {
            var effect = new Label { Text = skill.EffectHint };
            effect.AddStyleClass(StyleClass.Positive);
            row.AddChild(effect);
        }

        if (!string.IsNullOrWhiteSpace(skill.BlockReason))
        {
            var block = new Label { Text = skill.BlockReason };
            block.AddStyleClass(StyleClass.Negative);
            row.AddChild(block);
        }

        return row;
    }

    private static string FormatLevelBar(int current, int max)
    {
        var sb = new StringBuilder(max);
        for (var i = 1; i <= max; i++)
            sb.Append(i <= current ? '●' : '○');
        return sb.ToString();
    }
}
