using Content.Client.UserInterface.Controls;
using Content.Shared._Fish.ClockworkCult;
using Content.Shared._Fish.ClockworkCult.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Fish.ClockworkCult;

[GenerateTypedNameReferences]
public sealed partial class FishClockworkSlabWindow : FancyWindow
{
    public event Action<string>? OnRecite;

    public FishClockworkSlabWindow()
    {
        RobustXamlLoader.Load(this);
    }

    public void UpdateState(FishClockworkSlabBoundUserInterfaceState state)
    {
        var ark = state.ArkTimeRemaining is { } t
            ? $"{(int)t.TotalMinutes:00}:{t.Seconds:00}"
            : "--:--";

        StatusLabel.Text = Loc.GetString(
            "fish-clockwork-slab-status",
            ("power", (int)state.Power),
            ("vitality", (int)state.Vitality),
            ("servants", state.ServantCount),
            ("ark", ark),
            ("script", state.ScriptUnlocked),
            ("application", state.ApplicationUnlocked),
            ("herald", state.Heralded));

        ScriptureContainer.RemoveAllChildren();
        foreach (var entry in state.Scriptures)
        {
            var box = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
            };

            var tierLoc = entry.Tier switch
            {
                FishClockworkScriptureTier.Driver => Loc.GetString("fish-clockwork-scripture-tier-driver"),
                FishClockworkScriptureTier.Script => Loc.GetString("fish-clockwork-scripture-tier-script"),
                FishClockworkScriptureTier.Application => Loc.GetString("fish-clockwork-scripture-tier-application"),
                _ => entry.Tier.ToString(),
            };

            var label = new Label
            {
                Text = Loc.GetString(
                    "fish-clockwork-slab-entry",
                    ("name", entry.Name),
                    ("tier", tierLoc),
                    ("cost", $"{entry.PowerCost:0}"),
                    ("time", $"{entry.ChannelTime:0.#}")),
                HorizontalExpand = true,
                ToolTip = entry.UnavailableReason ?? entry.Description,
            };

            var button = new Button
            {
                Text = Loc.GetString("fish-clockwork-slab-recite"),
                Disabled = !entry.Available,
            };

            var id = entry.PrototypeId;
            button.OnPressed += _ => OnRecite?.Invoke(id);

            box.AddChild(label);
            box.AddChild(button);
            ScriptureContainer.AddChild(box);
        }
    }
}
