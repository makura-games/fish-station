using System;
using System.Collections.Generic;
using Content.Client.UserInterface.Controls;
using Content.Shared._Fish.CentCommSupply;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.IoC;
using Robust.Shared.Prototypes;

namespace Content.Client._Fish.CentCommSupply;

[GenerateTypedNameReferences]
public sealed partial class CentCommSupplyWindow : FancyWindow
{
    [Dependency] private IEntityManager _entity = default!;
    [Dependency] private IPrototypeManager _prototype = default!;

    private readonly SpriteSystem _sprite;
    private readonly List<NetEntity> _stationEntities = new();
    private readonly List<CentCommSupplyProductEntry> _products = new();
    private readonly Dictionary<string, CentCommSupplyProductEntry> _productsById = new();
    private readonly List<string> _categoryStrings = new();
    private readonly Dictionary<string, int> _order = new();
    private readonly CentCommSupplyOrderMenu _orderMenu;

    private string? _category;
    private NetEntity? _selectedStation;
    private NetEntity? _pendingStationSelection;
    private NetEntity? _stationSelectionPrevious;
    private Guid _pendingStationSelectionId;
    private CentCommSupplyProductEntry? _pendingProduct;
    private int _maxProductsPerOrder = int.MaxValue;
    private bool _stationSelectionPending;
    private bool _orderPending;
    private string? _orderLimitMessage;

    public event Func<NetEntity, Guid, bool>? OnStationSelected;
    public event Func<NetEntity, List<CentCommSupplyOrderEntry>, bool>? OnOrderPressed;

    public CentCommSupplyWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _sprite = _entity.System<SpriteSystem>();

        _orderMenu = new CentCommSupplyOrderMenu();
        _orderMenu.SubmitButton.OnPressed += _ => AddPendingProduct();

        StationSelector.OnItemSelected += args =>
        {
            if (args.Id < 0 || args.Id >= _stationEntities.Count)
                return;

            SelectStation(_stationEntities[args.Id]);
        };

        SearchBar.OnTextChanged += _ => PopulateProducts();
        Categories.OnItemSelected += args =>
        {
            _category = args.Id == 0 ? null : _categoryStrings[args.Id];
            Categories.SelectId(args.Id);
            PopulateProducts();
        };
        OrderButton.OnPressed += _ => SubmitOrder();
    }

    public void UpdateState(CentCommSupplyBoundUserInterfaceState state)
    {
        _maxProductsPerOrder = Math.Max(1, state.MaxProductsPerOrder);

        UpdateStations(state);

        _products.Clear();
        _products.AddRange(state.Products);
        _productsById.Clear();

        foreach (var product in _products)
            _productsById[product.PrototypeId] = product;

        PruneOrder();
        PopulateCategories();
        PopulateProducts();
        PopulateOrder();

        if (state.OrderPlaced)
        {
            _orderPending = false;
            ClearOrder();
        }
        else if (_orderPending && !string.IsNullOrWhiteSpace(state.StatusMessage))
        {
            _orderPending = false;
        }

        if (!string.IsNullOrWhiteSpace(state.StatusMessage))
        {
            StatusLabel.Visible = true;
            StatusLabel.Text = state.StatusMessage;
        }
        else
        {
            StatusLabel.Visible = false;
        }

        UpdateStationSelector();
        UpdateOrderButton();
    }

    /// <summary>
    /// Requests a station change and waits for the per-user server acknowledgement.
    /// </summary>
    public void SelectStation(NetEntity station)
    {
        if (_orderPending || _stationSelectionPending)
            return;

        if (!_stationEntities.Contains(station) || _selectedStation == station)
            return;

        _stationSelectionPrevious = _selectedStation;
        var selectionId = Guid.NewGuid();
        _selectedStation = station;
        _pendingStationSelection = station;
        _pendingStationSelectionId = selectionId;
        _stationSelectionPending = true;
        UpdateStationSelector();

        if (OnStationSelected?.Invoke(station, selectionId) == true)
            return;

        _selectedStation = _stationSelectionPrevious;
        _stationSelectionPrevious = null;
        _pendingStationSelection = null;
        _pendingStationSelectionId = Guid.Empty;
        _stationSelectionPending = false;
        RestoreStationSelectorSelection();
    }

    /// <summary>
    /// Applies the server response for the matching station selection request.
    /// </summary>
    public void OnStationSelectionResult(Guid selectionId, bool accepted, NetEntity? station, string? error)
    {
        if (!_stationSelectionPending || selectionId != _pendingStationSelectionId)
            return;

        _pendingStationSelection = null;
        _pendingStationSelectionId = Guid.Empty;
        _stationSelectionPending = false;

        if (accepted && station is { } acceptedStation && _stationEntities.Contains(acceptedStation))
        {
            if (_stationSelectionPrevious != acceptedStation)
                ClearOrder();

            _selectedStation = acceptedStation;
        }
        else
        {
            _selectedStation = _stationSelectionPrevious;
        }

        _stationSelectionPrevious = null;
        RestoreStationSelectorSelection();

        if (!string.IsNullOrWhiteSpace(error))
        {
            StatusLabel.Visible = true;
            StatusLabel.Text = error;
        }
    }

    protected override void Dispose(bool disposing)
    {
        base.Dispose(disposing);

        if (!disposing)
            return;

        _orderMenu.Dispose();
    }

    private void UpdateStations(CentCommSupplyBoundUserInterfaceState state)
    {
        var previousSelection = _selectedStation;
        var wasPending = _stationSelectionPending;

        StationSelector.Clear();
        _stationEntities.Clear();

        foreach (var (station, name) in state.AvailableStations)
        {
            _stationEntities.Add(station);
            StationSelector.AddItem(name);
        }

        if (_stationEntities.Count == 0)
        {
            _selectedStation = null;
            _pendingStationSelection = null;
            _stationSelectionPrevious = null;
            _pendingStationSelectionId = Guid.Empty;
            _stationSelectionPending = false;
            UpdateStationSelector();
            ClearOrder();
            return;
        }

        var serverSelected = state.SelectedStation;

        if (_stationSelectionPending)
        {
            var pending = _pendingStationSelection;
            if (pending is { } pendingStation && !_stationEntities.Contains(pendingStation))
            {
                _pendingStationSelection = null;
                _stationSelectionPrevious = null;
                _pendingStationSelectionId = Guid.Empty;
                _stationSelectionPending = false;
                _selectedStation = serverSelected is { } selected && _stationEntities.Contains(selected)
                    ? selected
                    : _stationEntities[0];
                ClearOrder();
            }
            else
            {
                // Fish-edit: общий state не должен сбрасывать ожидание чужого запроса
                _selectedStation = pending;
            }
        }
        else
        {
            _selectedStation = serverSelected is { } selected && _stationEntities.Contains(selected)
                ? selected
                : _stationEntities[0];
        }

        if (!wasPending && _selectedStation != previousSelection)
            ClearOrder();

        var selectedIndex = _selectedStation is { } current
            ? _stationEntities.IndexOf(current)
            : -1;

        if (selectedIndex < 0)
            selectedIndex = 0;

        _selectedStation = _stationEntities[selectedIndex];
        StationSelector.SelectId(selectedIndex);
        UpdateStationSelector();
    }

    private void PopulateCategories()
    {
        _categoryStrings.Clear();
        Categories.Clear();

        foreach (var product in _products)
        {
            if (!_categoryStrings.Contains(product.Category))
                _categoryStrings.Add(product.Category);
        }

        _categoryStrings.Sort();

        if (_category is { } selected && !_categoryStrings.Contains(selected))
            _category = null;

        _categoryStrings.Insert(0, Loc.GetString("centcomm-supply-window-categories-all"));

        foreach (var category in _categoryStrings)
            Categories.AddItem(category);

        Categories.SelectId(_category == null
            ? 0
            : Math.Max(1, _categoryStrings.IndexOf(_category)));
    }

    private void PopulateProducts()
    {
        Products.RemoveAllChildren();

        var search = SearchBar.Text.Trim();
        foreach (var product in _products)
        {
            if (_category != null && product.Category != _category)
                continue;

            if (search.Length != 0
                && !product.Name.Contains(search, StringComparison.OrdinalIgnoreCase)
                && !(product.Description?.Contains(search, StringComparison.OrdinalIgnoreCase) ?? false))
            {
                continue;
            }

            var ordered = _order.TryGetValue(product.PrototypeId, out var amount) ? amount : 0;
            var row = new CentCommSupplyProductRow
            {
                ProductName = { Text = product.Name },
                MainButton = { ToolTip = product.Description ?? string.Empty },
                ProductQuantity =
                {
                    Text = Loc.GetString("centcomm-supply-window-product-quantity",
                        ("count", ordered),
                        ("max", product.MaxQuantity)),
                },
            };

            var icon = GetIcon(product.PrototypeId);
            if (icon != null)
                row.Icon.Texture = icon;
            else
                row.Icon.Visible = false;

            var selectedProduct = product;
            row.MainButton.OnPressed += _ => OpenOrderMenu(selectedProduct);
            Products.AddChild(row);
        }
    }

    private void PopulateOrder()
    {
        Order.RemoveAllChildren();

        foreach (var (productId, quantity) in _order)
        {
            if (!_productsById.TryGetValue(productId, out var product))
                continue;

            var row = new CentCommSupplyOrderRow(product, quantity);

            var icon = GetIcon(product.PrototypeId);
            if (icon != null)
                row.Icon.Texture = icon;
            else
                row.Icon.Visible = false;

            row.Remove.OnPressed += _ => RemoveProduct(productId);
            Order.AddChild(row);
        }

        UpdateOrderButton();
    }

    private void OpenOrderMenu(CentCommSupplyProductEntry product)
    {
        if (_orderPending || _stationSelectionPending)
            return;

        if (!_productsById.TryGetValue(product.PrototypeId, out var current))
            return;

        _pendingProduct = current;
        _orderMenu.SetProduct(current);
        _orderMenu.OpenCentered();
        _orderMenu.SetPositionLast();
    }

    private void AddPendingProduct()
    {
        if (_orderPending || _stationSelectionPending)
            return;

        if (_pendingProduct is not { } pending)
            return;

        if (!_productsById.TryGetValue(pending.PrototypeId, out var product))
        {
            _pendingProduct = null;
            _orderMenu.Close();
            return;
        }

        var amount = _orderMenu.Amount.Value;
        if (amount < 1)
            return;

        var current = _order.TryGetValue(product.PrototypeId, out var existing) ? existing : 0;
        if (current <= 0 && _order.Count >= _maxProductsPerOrder)
        {
            StatusLabel.Visible = true;
            StatusLabel.Text = Loc.GetString("centcomm-supply-error-too-many-products",
                ("max", _maxProductsPerOrder));
            return;
        }

        _order[product.PrototypeId] = Math.Min(product.MaxQuantity, current + amount);

        PopulateProducts();
        PopulateOrder();
        _orderMenu.Close();
    }

    private void RemoveProduct(string productId)
    {
        if (_orderPending || _stationSelectionPending)
            return;

        if (!_order.Remove(productId))
            return;

        PopulateProducts();
        PopulateOrder();
    }

    private void SubmitOrder()
    {
        if (_orderPending || _stationSelectionPending)
            return;

        if (_selectedStation is not { } station)
        {
            StatusLabel.Visible = true;
            StatusLabel.Text = Loc.GetString("centcomm-supply-window-no-station");
            return;
        }

        if (_order.Count == 0)
        {
            StatusLabel.Visible = true;
            StatusLabel.Text = Loc.GetString("centcomm-supply-window-empty-order");
            return;
        }

        var entries = new List<CentCommSupplyOrderEntry>(_order.Count);
        foreach (var (productId, quantity) in _order)
            entries.Add(new CentCommSupplyOrderEntry(productId, quantity));

        _orderPending = true;
        UpdateOrderButton();

        if (OnOrderPressed?.Invoke(station, entries) == true)
            return;

        _orderPending = false;
        UpdateOrderButton();
    }

    private void ClearOrder()
    {
        _order.Clear();
        _pendingProduct = null;

        if (_orderMenu.IsOpen)
            _orderMenu.Close();

        PopulateProducts();
        Order.RemoveAllChildren();
        UpdateOrderButton();
    }

    private void PruneOrder()
    {
        List<string>? remove = null;

        foreach (var productId in _order.Keys)
        {
            if (!_productsById.ContainsKey(productId))
                (remove ??= new()).Add(productId);
        }

        if (remove == null)
            return;

        foreach (var productId in remove)
            _order.Remove(productId);
    }

    private void UpdateOrderButton()
    {
        var limitMessage = GetOrderLimitMessage();

        if (limitMessage != null)
        {
            StatusLabel.Visible = true;
            StatusLabel.Text = limitMessage;
        }
        else if (_orderLimitMessage != null)
        {
            StatusLabel.Visible = false;
        }

        _orderLimitMessage = limitMessage;
        OrderButton.Disabled = _orderPending
            || _stationSelectionPending
            || _selectedStation == null
            || _order.Count == 0
            || limitMessage != null;
    }

    /// <summary>
    /// Returns a message when the current order exceeds a limit, otherwise null.
    /// </summary>
    private string? GetOrderLimitMessage()
    {
        if (_order.Count > _maxProductsPerOrder)
        {
            return Loc.GetString("centcomm-supply-window-order-too-many-products",
                ("max", _maxProductsPerOrder));
        }

        foreach (var (productId, quantity) in _order)
        {
            if (!_productsById.TryGetValue(productId, out var product))
                continue;

            var max = Math.Max(1, product.MaxQuantity);
            if (quantity <= max)
                continue;

            return Loc.GetString("centcomm-supply-window-order-invalid-quantity",
                ("product", product.Name),
                ("max", max));
        }

        return null;
    }

    private void UpdateStationSelector()
    {
        StationSelector.Disabled = _orderPending
            || _stationSelectionPending
            || _stationEntities.Count == 0;
    }

    /// <summary>
    /// Restores the selector to the current selection after a rejected change.
    /// </summary>
    private void RestoreStationSelectorSelection()
    {
        var index = _selectedStation is { } station
            ? _stationEntities.IndexOf(station)
            : -1;

        if (index >= 0)
            StationSelector.SelectId(index);

        UpdateStationSelector();
        UpdateOrderButton();
    }

    private Texture? GetIcon(string prototypeId)
    {
        if (!_prototype.TryIndex<CentCommSupplyProductPrototype>(prototypeId, out var prototype)
            || prototype.Icon == null)
        {
            return null;
        }

        return _sprite.Frame0(prototype.Icon);
    }
}
