using System.Collections.Generic;
using Content.Shared._Fish.CentCommSupply;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Fish.CentCommSupply;

[GenerateTypedNameReferences]
public sealed partial class CentCommSupplyOrderMenu : DefaultWindow
{
    public CentCommSupplyOrderMenu()
    {
        RobustXamlLoader.Load(this);
        Amount.SetButtons(new List<int> { -3, -2, -1 }, new List<int> { 1, 2, 3 });
    }

    public void SetProduct(CentCommSupplyProductEntry product)
    {
        Title = product.Name;
        ProductName.Text = product.Name;

        var description = product.Description ?? string.Empty;
        Description.SetMessage(FormattedMessage.FromUnformatted(description));
        Description.Visible = !string.IsNullOrWhiteSpace(description);

        Amount.Value = 1;
        Amount.IsValid = value => value >= 1 && value <= product.MaxQuantity;
    }
}
